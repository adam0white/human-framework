"""Generate public host cast records. Author-only secrets stay in the registry."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[1]
text=(root/'docs/lab/cast-registry.md').read_text()
traits='honesty emotionality extraversion agreeableness conscientiousness openness'.split()
values='benevolence universalism tradition conformity security achievement power hedonism stimulation selfDirection'.split()
rows={}
for line in text.splitlines():
 m=re.match(r'\| `(hf\.cast\.[^`]+)` \| ([^|]+) \| (\d+) \| (Coast|Valley) \| (\d+) \| ([^|]+) \|',line)
 if m:
  cid,name,age,cohort,rev,games=m.groups()
  rows[cid]=dict(castId=cid,name=name.strip(),age=int(age),cohort=cohort.lower(),revision=rev,games=[{'The Rope':'rope','Murmur':'murmur','Voice':'voice','Well':'well','Watch':'watch','Small Works':'repair','Good Hands':'goodhands'}.get(g.strip(),g.strip().lower()) for g in games.split(';')])
for section in re.split(r'\n### \d+\. ',text)[1:41]:
 cid=re.search(r'\*\*Identity:\*\* `(hf\.cast\.[^`]+)`',section).group(1)
 row=rows[cid]
 profile=re.search(r'\*\*HF profile:\*\* (.*?) These are',section,re.S).group(1)
 numbers=dict((k,float(v)) for k,v in re.findall(r'([A-Za-z]+) (\.\d+|0\.\d+)',profile))
 row['traits']={k:numbers.get(k,.5) for k in traits}
 row['values']={k:numbers.get(k,.5) for k in values}
 row['place']=re.search(r'\*\*Place:\*\* (.*?) \*\*Work:',section).group(1)
 row['work']=re.search(r'\*\*Work:\*\* (.*?) \*\*Family:',section).group(1)
 # Public introduction is the first authored paragraph only. Later paragraphs include private facts.
 row['introduction']=section.split('**Authored life**\n\n')[1].split('\n\n')[0]
assignments = [
 ('canteen cold station','daytime meal placement'), ('local parcel round','depot sorting assignment'),
 ('ward night shift','qualified nursing relief shift'), ('office records desk','office correspondence desk'),
 ('bench repairs','repair estimates'), ('bread-delivery help','tea-house errands'),
 ('neighbour meal help','neighbour shopping help'), ('market stall','supplier orders'),
 ('grill station','grill preparation'), ('cold station','shared-kitchen planning'),
 ('dish station','supervised repair preparation'), ('oven station','catered meal preparation'),
 ('placement interviews','placement scheduling'), ('tea garden service','household meal preparation'),
 ('school kitchen','private meal preparation'), ('courier round','depot logistics desk'),
 ('depot sorting supervision','depot dispatch supervision'), ('accounts ledger','invoice reconciliation'),
 ('volunteer reading tutor','volunteer practical-writing tutor'), ('retired routine','voluntary ferry-history notes'),
 ('climbing instruction','route safety preparation'), ('photography assignment','photograph editing'),
 ('library desk','library shelving'), ('maintenance inspection','maintenance repair assignment'),
 ('field observation','ecology survey preparation'), ('dam inspection','dam records'),
 ('dam observation round','dam gauge records'), ('inn service','inn stores'),
 ('repair design','repair making'), ('supervised repair bench','kitchen assistance'),
 ('meal preparation','seed-store organisation'), ('building repair','household flock care'),
 ('supervised building preparation','supervised building assistance'), ('woodland work','forest-edge inspection'),
 ('gathering route','bounded watch observation'), ('well maintenance','grain-store work'),
 ('retired advisory routine','well-digging advice'), ('supervised surveying','household work'),
 ('communal watch','watch equipment preparation'), ('supervised watch running','supervised stores assistance')]
assert len(rows)==len(assignments)==40
for row, jobs in zip(rows.values(),assignments):
 row['assignments'] = list(jobs)
assert set(g for row in rows.values() for g in row['games']) == set('pass murmur stairwell voice goodhands hearsay rope glance repair neighbours commonstead well valley warren watch'.split())
out='/** Generated by scripts/cast-artifact.py. Public opening facts only; secrets stay author-side. */\nimport type { Traits, ValueId } from "@adam0white/human-framework";\nexport interface CanonicalCast { castId: string; name: string; age: number; cohort: "coast" | "valley"; revision: string; games: string[]; traits: Traits; values: Record<ValueId, number>; place: string; work: string; introduction: string; assignments: string[] }\nexport const CAST_EDITION = "one-cast-1";\nexport const CANONICAL_CAST: readonly CanonicalCast[] = '+json.dumps(list(rows.values()),ensure_ascii=False,indent=2)+';\nexport function canonicalCast(castId: string): CanonicalCast { const p = CANONICAL_CAST.find(p => p.castId === castId); if (!p) throw new Error("Unknown canonical person."); return structuredClone(p); }\nexport function castForGame(game: string): CanonicalCast[] { return CANONICAL_CAST.filter(p => p.games.includes(game)).map(p => structuredClone(p)); }\n'
(root/'packages/lab-client/src/cast.ts').write_text(out)
