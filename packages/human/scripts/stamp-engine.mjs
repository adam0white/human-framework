// Core identity excludes host commits, documentation, timestamps and absolute paths.
// The generated literal travels unchanged with compiled and packed consumers.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const files = [];
async function visit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await visit(path);
    else if (entry.name.endsWith('.ts') && entry.name !== 'run-engine.ts') files.push(path);
  }
}
await visit(join(root, 'src'));
files.sort();
const sources = [];
for (const path of files) sources.push([relative(root, path), digest(await readFile(path))]);
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const contract = Object.fromEntries(
  ['name', 'version', 'type', 'engines', 'exports', 'dependencies']
    .filter((key) => key in manifest)
    .map((key) => [key, manifest[key]]),
);
const compiler = createRequire(import.meta.url)('typescript/package.json');
const configuration = [];
for (const path of [
  'tsconfig.build.json',
  'tsconfig.json',
  '../../tsconfig.base.json',
  'scripts/stamp-engine.mjs',
])
  configuration.push([path, digest(await readFile(join(root, path)))]);
const build = digest(
  JSON.stringify({
    domain: 'hf-run4/core-source/v1',
    contract,
    sources,
    configuration,
    compiler: { name: compiler.name, version: compiler.version },
  }),
);
const schema = digest(await readFile(join(root, 'src/run-schema.ts')));
const engine = { package: `${manifest.name}@${manifest.version}`, build, schema };
const literal = (value) =>
  `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n').replaceAll('\r', '\\r')}'`;
const text = `// Generated by scripts/stamp-engine.mjs. Do not edit.\nexport const RUN_ENGINE = Object.freeze({\n  package: ${literal(engine.package)},\n  build: ${literal(build)},\n  schema: ${literal(schema)},\n});\n`;
const target = join(root, 'src/run-engine.ts');
const committed = await readFile(target, 'utf8').catch(() => '');
// --check fails on a stale stamp instead of writing; release runs it so a tag never carries one.
if (process.argv.includes('--check')) {
  if (committed !== text) {
    process.stderr.write('src/run-engine.ts is stale; run `npm run build` in packages/human and commit it\n');
    process.exit(1);
  }
} else if (committed !== text) await writeFile(target, text);
// stderr: npm pack --json captures stdout during prepack, and release.ts parses it.
process.stderr.write(`${JSON.stringify({ ...engine, sourceFiles: sources.length })}\n`);
